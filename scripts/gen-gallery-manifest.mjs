// 갤러리 카테고리 매니페스트 생성기
// src/assets/photos/gallery/<카테고리>/ 폴더들을 스캔해 static import 매니페스트를 만든다.
// 사진 추가/삭제 후 실행: npm run gallery
// - 카테고리 안 파일명 정렬 첫 번째 = 기본 링크에서 보여줄 사진
// - EXIF 회전 사진(orientation ≥ 5)은 경고 출력 (무손실 회전 정리 필요)
import fs from "fs";
import path from "path";
import sharp from "sharp";

const ROOT = "src/assets/photos/gallery";
const OUT = "src/lib/gallery-manifest.ts";
const IMG_RE = /\.(jpe?g|png|webp)$/i;

const categories = fs
  .readdirSync(ROOT)
  .filter((d) => fs.statSync(path.join(ROOT, d)).isDirectory())
  .sort();

const imports = [];
const rows = [];
let warned = false;

for (const cat of categories) {
  const files = fs
    .readdirSync(path.join(ROOT, cat))
    .filter((f) => IMG_RE.test(f))
    .sort();
  if (files.length === 0) continue;

  const vars = [];
  for (const [i, f] of files.entries()) {
    if (/\.(JPG|JPEG|PNG|WEBP)$/.test(f)) {
      console.warn(
        `⚠️  대문자 확장자: gallery/${cat}/${f} — blur placeholder가 생성되지 않아요. 소문자(.jpg)로 바꿔주세요.`,
      );
      warned = true;
    }
    const varName = `g${cat}_${i}`;
    imports.push(
      `import ${varName} from "@/assets/photos/gallery/${cat}/${f}";`,
    );
    vars.push(varName);

    const meta = await sharp(path.join(ROOT, cat, f)).metadata();
    if ((meta.orientation ?? 1) >= 5) {
      console.warn(
        `⚠️  EXIF 회전 감지: gallery/${cat}/${f} — 프레임 비율이 어긋납니다. 무손실 회전 정리가 필요해요.`,
      );
      warned = true;
    }
  }
  rows.push(`  [${vars.join(", ")}], // ${cat} (${files.length}장)`);
}

const content = `// AUTO-GENERATED by scripts/gen-gallery-manifest.mjs — 직접 수정하지 마세요.
// 재생성: npm run gallery
import type { StaticImageData } from "next/image";
${imports.join("\n")}

export const GALLERY_CATEGORIES: StaticImageData[][] = [
${rows.join("\n")}
];
`;

fs.writeFileSync(OUT, content);
console.log(
  `generated ${OUT}: 카테고리 ${rows.length}개, 총 ${imports.length}장${warned ? " (⚠️ EXIF 경고 있음)" : ""}`,
);
