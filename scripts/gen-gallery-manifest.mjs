// 갤러리 매니페스트 생성기
// src/assets/photos/gallery/ 하위를 스캔해 static import 매니페스트를 만든다.
// 사진 추가/삭제 후 실행: npm run gallery
//
//  - 01~12 등 숫자 폴더 = 랜덤 풀 (기본 링크에서 폴더별 1장씩 랜덤)
//  - fix 폴더          = 고정 세트 (?t=p 링크에서 이 폴더 전체를 순서대로)
//  - EXIF 회전(orientation ≥ 5)·대문자 확장자는 경고 출력
import fs from "fs";
import path from "path";
import sharp from "sharp";

const ROOT = "src/assets/photos/gallery";
const OUT = "src/lib/gallery-manifest.ts";
const FIX_DIR = "fix";
const IMG_RE = /\.(jpe?g|png|webp)$/i;

const imports = [];
let warned = false;

// 한 폴더를 스캔해 import 문을 쌓고 변수명 목록을 돌려준다
async function scanDir(dir, prefix) {
  const files = fs
    .readdirSync(path.join(ROOT, dir))
    .filter((f) => IMG_RE.test(f))
    .sort();

  const vars = [];
  for (const [i, f] of files.entries()) {
    if (/\.(JPG|JPEG|PNG|WEBP)$/.test(f)) {
      console.warn(
        `⚠️  대문자 확장자: gallery/${dir}/${f} — blur placeholder가 생성되지 않아요. 소문자(.jpg)로 바꿔주세요.`,
      );
      warned = true;
    }
    const varName = `${prefix}_${i}`;
    imports.push(`import ${varName} from "@/assets/photos/gallery/${dir}/${f}";`);
    vars.push(varName);

    const meta = await sharp(path.join(ROOT, dir, f)).metadata();
    if ((meta.orientation ?? 1) >= 5) {
      console.warn(
        `⚠️  EXIF 회전 감지: gallery/${dir}/${f} — 프레임 비율이 어긋납니다. 무손실 회전 정리가 필요해요.`,
      );
      warned = true;
    }
  }
  return vars;
}

const dirs = fs
  .readdirSync(ROOT)
  .filter((d) => fs.statSync(path.join(ROOT, d)).isDirectory())
  .sort();

// 고정 세트
const fixVars = dirs.includes(FIX_DIR) ? await scanDir(FIX_DIR, "gfix") : [];
if (fixVars.length === 0) {
  console.warn(`⚠️  gallery/${FIX_DIR} 폴더가 비어 있어요 — ?t=p도 랜덤으로 동작합니다.`);
}

// 랜덤 풀 (fix 제외)
const rows = [];
for (const cat of dirs.filter((d) => d !== FIX_DIR)) {
  const vars = await scanDir(cat, `g${cat}`);
  if (vars.length === 0) continue;
  rows.push(`  [${vars.join(", ")}], // ${cat} (${vars.length}장)`);
}

const content = `// AUTO-GENERATED by scripts/gen-gallery-manifest.mjs — 직접 수정하지 마세요.
// 재생성: npm run gallery
import type { StaticImageData } from "next/image";
${imports.join("\n")}

// 기본 링크: 카테고리별 1장씩 랜덤
export const GALLERY_CATEGORIES: StaticImageData[][] = [
${rows.join("\n")}
];

// ?t=p 링크: gallery/fix 폴더를 파일명 순서대로 고정 노출
export const GALLERY_FIXED: StaticImageData[] = [${
  fixVars.length ? `\n  ${fixVars.join(",\n  ")},\n` : ""
}];
`;

fs.writeFileSync(OUT, content);
console.log(
  `generated ${OUT}: 랜덤 카테고리 ${rows.length}개 · 고정 ${fixVars.length}장 · 총 ${imports.length}장${
    warned ? " (⚠️ 경고 있음)" : ""
  }`,
);
